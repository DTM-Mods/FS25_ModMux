"""Writes config/gameActions.xml: the game's own input actions with the situations they work in (category: ONFOOT,
VEHICLE, SYSTEM, MENU..., space separated), taken from the SDK's sdk/xmlDoku/inputActions.xml. ModMux's KEYS tab uses
it to tell real key conflicts (two actions that can fire in the same situation) from harmless shared keys. Run again
after a game update.
Usage: python -I tools/make_game_actions.py [path to inputActions.xml]"""
import pathlib
import sys
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

project = pathlib.Path(__file__).resolve().parent.parent
source = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else
                      r"C:\Program Files (x86)\Steam\steamapps\common\Farming Simulator 25\sdk\xmlDoku\inputActions.xml")
actions = []
for action in ET.parse(source).getroot().iter("action"):
    name = action.get("name")
    if name:
        actions.append((name, " ".join((action.get("category") or "").split())))

lines = ['<?xml version="1.0" encoding="utf-8" standalone="no"?>',
         "<!-- generated by tools/make_game_actions.py from the game's sdk/xmlDoku/inputActions.xml: the game's input actions",
         "     and the situations they work in. ModMux's KEYS tab reads it; don't edit by hand. -->",
         "<gameActions>"]
for name, category in actions:
    lines.append(f"    <action name={quoteattr(name)} category={quoteattr(category)}/>")
lines += ["</gameActions>", ""]
out = project / "config" / "gameActions.xml"
out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(out, len(actions), "actions")
