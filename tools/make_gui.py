"""Writes gui/ModMuxFrame.xml (the ModMux page layout). The repeated parts (6 tab buttons, 4 column headings,
24 detail lines) are generated here so their positions stay in step.
Usage: python -I tools/make_gui.py"""
import pathlib
import xml.etree.ElementTree as ET

project = pathlib.Path(__file__).resolve().parent.parent
TAB_KEYS = ["mm_tab_overview", "mm_tab_conflicts", "mm_tab_keys", "mm_tab_errors", "mm_tab_live", "mm_tab_vehicle",
            "mm_tab_performance", "mm_tab_review", "mm_tab_profiles"]
COLUMNS = [(-51, 420), (377, 230), (617, 150), (773, 152)]   # x, width of the column headings (list starts at -63)
DETAIL_LINES = 24

tabs = "\n".join(f'''            <Button profile="mm_tab" id="mainTabs[{i}]" text="$l10n_{key}" onClick="onClickTab{i}">
                <ThreePartBitmap profile="fs25_subCategorySelectorTabbedTabBg" name="background"/>
            </Button>''' for i, key in enumerate(TAB_KEYS, 1))
heads = "\n".join(f'            <Text profile="mm_colHead" id="colHead[{i}]" position="{x}px -34px" size="{w}px 28px"/>'
                  for i, (x, w) in enumerate(COLUMNS, 1))
details = "\n".join(f'                <Text profile="mm_detailLine" id="detailLine[{i}]" position="18px {-52 - (i - 1) * 26}px"/>'
                    for i in range(1, DETAIL_LINES + 1))

XML = f'''<?xml version="1.0" encoding="utf-8" standalone="no" ?>
<!-- ModMux page (generated by tools/make_gui.py). Same frame as the game's own menu pages (header, tab
     bar, tabbed container); the content: a sub header line, column headings, the list (1000px) on the left and the
     details panel (560px) on the right, footer under the bottom line. The tab container's content is inset 63px, so
     the list starts at x -63px. Bitmaps named mmImg_* get gui/modMux_ui.dds (plain white) in code and are tinted by
     their profile: a Bitmap without its own image draws the whole game GUI atlas (seen in game by Player Trading+). -->
<GUI name="ModMuxFrame">
    <GuiElement profile="fs25_menuContainer">
        <GuiElement profile="fs25_menuHeaderPanel" position="-62px 92px">
            <Bitmap profile="fs25_menuHeaderIconBg">
                <Bitmap profile="fs25_menuHeaderIcon" id="headerIcon"/>
            </Bitmap>
            <Text profile="fs25_menuHeaderTitle" text="$l10n_mm_menuTitle"/>
        </GuiElement>

        <BoxLayout profile="fs25_subCategorySelectorTabbedBox">
{tabs}
        </BoxLayout>
        <ThreePartBitmap profile="fs25_lineSeparatorTopHighlighted" position="-63px -57px" size="100% 2dp"/>
        <MultiTextOption profile="fs25_subCategorySelectorTabbed" id="mainPaging" position="0px -10px" onClick="onClickMainPaging"/>

        <GuiElement profile="fs25_subCategorySelectorTabbedContainer">
            <Text profile="mm_subHeader" id="subHeader" position="-63px 0px"/>

{heads}
            <ThreePartBitmap profile="fs25_lineSeparatorTop" position="-63px -64px" size="1000px 1dp"/>

            <SmoothList profile="mm_list" id="rowList" position="-63px -70px" size="1000px 646px" listItemSpacing="4px">
                <ListItem profile="mm_rowItem">
                    <Bitmap profile="mm_rowBg" name="mmImg_row"/>
                    <Text profile="mm_cell" name="c1" position="12px 0px" size="420px 40px"/>
                    <Text profile="mm_cell" name="c2" position="440px 0px" size="230px 40px"/>
                    <Text profile="mm_cell" name="c3" position="680px 0px" size="150px 40px"/>
                    <Text profile="mm_cellStatus" name="c4" position="836px 0px" size="152px 40px"/>
                </ListItem>
            </SmoothList>
            <Text profile="mm_emptyText" id="emptyText" position="-63px -320px"/>

            <GuiElement profile="mm_detailBox" position="957px -34px">
                <Bitmap profile="mm_detailEdge" name="mmImg_edge"/>
                <Bitmap profile="mm_detailBg" name="mmImg_bg"/>
                <Text profile="mm_detailTitle" id="detailTitle"/>
{details}
            </GuiElement>

            <ThreePartBitmap profile="fs25_lineSeparatorTop" position="-63px -723px" size="100% 1dp"/>
            <Text profile="mm_footer" id="footerText" position="-43px -733px"/>
        </GuiElement>
    </GuiElement>

    <GUIProfiles>
        <Profile name="mm_tab" extends="fs25_subCategorySelectorTabbedTab">
            <size value="175px 57px"/>
        </Profile>

        <Profile name="mm_subHeader" extends="baseReference" with="anchorTopLeft">
            <size value="1580px 28px"/>
            <textSize value="15px"/>
            <textBold value="true"/>
            <textUpperCase value="true"/>
            <textColor value="0.667 0.667 0.647 1"/>
            <textAlignment value="left"/>
            <textVerticalAlignment value="middle"/>
        </Profile>

        <Profile name="mm_colHead" extends="baseReference" with="anchorTopLeft">
            <textSize value="14px"/>
            <textBold value="true"/>
            <textUpperCase value="true"/>
            <textColor value="0.431 0.439 0.412 1"/>
            <textAlignment value="left"/>
            <textVerticalAlignment value="middle"/>
        </Profile>

        <Profile name="mm_list" extends="emptyPanel" with="pivotTopLeft">
            <size value="1000px 646px"/>
        </Profile>

        <!-- a row: dark card, green tint when selected -->
        <Profile name="mm_rowItem" extends="baseReference" with="anchorTopStretchingX">
            <height value="40px"/>
            <imageColor value="0 0 0 0"/>
            <imageSelectedColor value="0 0 0 0"/>
            <imageFocusedColor value="0 0 0 0"/>
            <imageHighlightedColor value="0 0 0 0"/>
        </Profile>
        <Profile name="mm_rowBg" extends="baseReference" with="anchorTopLeft">
            <size value="1000px 40px"/>
            <imageColor value="0.110 0.114 0.106 1"/>
            <imageSelectedColor value="0.196 0.235 0.110 1"/>
            <imageHighlightedColor value="0.150 0.170 0.110 1"/>
        </Profile>
        <Profile name="mm_cell" extends="baseReference" with="anchorTopLeft">
            <textSize value="15px"/>
            <textColor value="0.922 0.922 0.922 1"/>
            <textSelectedColor value="1 1 1 1"/>
            <textAlignment value="left"/>
            <textVerticalAlignment value="middle"/>
            <textLayoutMode value="scrolling"/>
        </Profile>
        <Profile name="mm_cellStatus" extends="mm_cell">
            <textBold value="true"/>
            <textUpperCase value="true"/>
            <textSize value="13px"/>
            <textColor value="0.667 0.667 0.647 1"/>
            <textSelectedColor value="0.804 0.804 0.784 1"/>
            <textAlignment value="right"/>
        </Profile>

        <Profile name="mm_emptyText" extends="baseReference" with="anchorTopLeft">
            <size value="1000px 40px"/>
            <textSize value="18px"/>
            <textColor value="$preset_fs25_colorGreyText"/>
            <textAlignment value="center"/>
            <textVerticalAlignment value="middle"/>
        </Profile>

        <!-- details panel -->
        <Profile name="mm_detailBox" extends="emptyPanel" with="anchorTopLeft">
            <size value="560px 680px"/>
        </Profile>
        <Profile name="mm_detailEdge" extends="baseReference" with="anchorTopLeft">
            <size value="560px 680px"/>
            <imageColor value="0.180 0.188 0.169 1"/>
        </Profile>
        <Profile name="mm_detailBg" extends="baseReference" with="anchorTopLeft">
            <position value="1px -1px"/>
            <size value="558px 678px"/>
            <imageColor value="0.110 0.114 0.106 1"/>
        </Profile>
        <Profile name="mm_detailTitle" extends="baseReference" with="anchorTopLeft">
            <position value="18px -10px"/>
            <size value="524px 32px"/>
            <textSize value="19px"/>
            <textBold value="true"/>
            <textColor value="$preset_colorWhite"/>
            <textAlignment value="left"/>
            <textVerticalAlignment value="middle"/>
            <textLayoutMode value="scrolling"/>
        </Profile>
        <Profile name="mm_detailLine" extends="baseReference" with="anchorTopLeft">
            <size value="524px 26px"/>
            <textSize value="15px"/>
            <textColor value="0.804 0.804 0.784 1"/>
            <textAlignment value="left"/>
            <textVerticalAlignment value="middle"/>
        </Profile>

        <Profile name="mm_footer" extends="baseReference" with="anchorTopLeft">
            <size value="1540px 30px"/>
            <textSize value="16px"/>
            <textColor value="$preset_fs25_colorGreyText"/>
            <textAlignment value="left"/>
            <textVerticalAlignment value="middle"/>
        </Profile>
    </GUIProfiles>
</GUI>
'''

out = project / "gui" / "ModMuxFrame.xml"
out.parent.mkdir(exist_ok=True)
out.write_text(XML, encoding="utf-8", newline="\n")
ET.parse(out)
print(out, "written,", len(XML), "bytes")
